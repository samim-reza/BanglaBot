/** Shapes of the public website's solution pages (one AgentSolution per business type). */

import type { LucideIcon } from "lucide-react";

/** Matches the backend's vertical keys (also used as ?type= on the contact form and ?vertical= on signup). */
export type AgentKey =
  | "clinic"
  | "dental"
  | "vet"
  | "restaurant"
  | "salon"
  | "real_estate"
  | "home_service"
  | "ecommerce"
  | "custom";

export type ChatLine = { who: "agent" | "caller"; text: string };

export type ExampleConversation = {
  business: string;
  channel: "Inbound call" | "Outbound call" | "Website chat";
  lines: ChatLine[];
  result: { label: string; detail: string };
};

export type AgentSolution = {
  key: AgentKey;
  /** URL segment under /solutions. */
  slug: string;
  name: string;
  agentName: string;
  icon: LucideIcon;
  forWho: string;
  tagline: string;
  summary: string;
  directions: string;
  capabilities: string[];
  setup: string[];
  outcomes: { label: string; detail: string }[];
  safety: string[];
  example: ExampleConversation;
};

/** A recorded sample call for the "Hear it" player (data generated by backend/scripts/demo_audio.py). */
export type SampleCall = {
  key: string;
  vertical: AgentKey;
  title: string;
  business: string;
  /** Path under /public. */
  src: string;
  /** Seconds. */
  duration: number;
  result: string;
  /** Waveform: loudness of equal slices of the audio, 0–1. */
  peaks: number[];
  /** `at` = seconds into the audio when the line starts. */
  lines: (ChatLine & { at: number })[];
};
